export function loadCustomTrends() {
  try {
    const raw = localStorage.getItem(STORAGE_CUSTOM_TRENDS);
    const parsed = raw ? JSON.parse(raw) : [];
    return Array.isArray(parsed) ? parsed : [];
  } catch {
    return [];
  }
}

export function saveCustomTrend(item) {
  const list = loadCustomTrends();
  const next = [{ id: `custom_${Date.now()}`, isCustom: true, ...item }, ...list].slice(0, 40);
  try {
    localStorage.setItem(STORAGE_CUSTOM_TRENDS, JSON.stringify(next));
  } catch {
    /* ignore */
  }
  return next;
}

export function deleteCustomTrend(id) {
  const next = loadCustomTrends().filter((x) => x.id !== id);
  try {
    localStorage.setItem(STORAGE_CUSTOM_TRENDS, JSON.stringify(next));
  } catch {
    /* ignore */
  }
  return next;
}

export function getAllTrendingProducts() {
  return [...loadCustomTrends(), ...DEFAULT_TRENDING_PRODUCTS];
}

export function calcCommissionBaht(price, pct) {
  return Math.round(((Number(price) || 0) * (Number(pct) || 0)) / 100);
}

export function filterAndSortTrends(items, { query = '', category = 'all', platform = 'all', minSales = 500, sortBy = 'sales' } = {}) {
  const q = String(query || '').trim().toLowerCase();
  const minS = Number(minSales) || 0;

  const filtered = items.filter((p) => {
    if ((Number(p.sales) || 0) < minS) return false;
    if (category !== 'all' && p.category !== category) return false;
    if (platform !== 'all' && p.platform !== platform) return false;
    if (q) {
      const hay = `${p.name} ${p.categoryLabel} ${p.benefits} ${p.hookIdea} ${p.platform}`.toLowerCase();
      if (!hay.includes(q)) return false;
    }
    return true;
  });

  return filtered.sort((a, b) => {
    if (sortBy === 'commission') {
      return calcCommissionBaht(b.price, b.commissionPct) - calcCommissionBaht(a.price, a.commissionPct);
    }
    if (sortBy === 'growth') {
      return (Number(b.growth7d) || 0) - (Number(a.growth7d) || 0);
    }
    if (sortBy === 'viral') {
      return (Number(b.viralScore) || 0) - (Number(a.viralScore) || 0);
    }
    return (Number(b.sales) || 0) - (Number(a.sales) || 0);
  });
}

export function formatSalesShort(n) {
  const num = Number(n) || 0;
  if (num >= 1000) return `${(num / 1000).toFixed(1).replace(/\.0$/, '')}k`;
  return String(num);
}
